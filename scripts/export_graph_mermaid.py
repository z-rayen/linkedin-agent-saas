"""Generate the Mermaid diagrams of the LangGraph graphs from the code itself.

Run from the repository root:
    PYTHONPATH=backend/src python scripts/export_graph_mermaid.py

The structure comes from build_graph(); no dependency is called. The outputs are docs/graphs/application_graph.md
and docs/graphs/research_graph.md.
"""

from pathlib import Path

from linkedin_agent.core.settings import DEFAULT_RESEARCH_LANGUAGES
from linkedin_agent.graphs.application_graph import GraphDeps
from linkedin_agent.graphs.application_graph import build_graph as build_application_graph
from linkedin_agent.graphs.research_graph import ResearchDeps, ResearchLimits
from linkedin_agent.graphs.research_graph import build_graph as build_research_graph
from linkedin_agent.graphs.watch_graph import WatchDeps, WatchLimits
from linkedin_agent.graphs.watch_graph import build_graph as build_watch_graph

GRAPHS_DIR = Path(__file__).resolve().parents[1] / "docs" / "graphs"


async def _unused(*_: object) -> None:
    raise RuntimeError("structure export only: no dependency may be called")


def _write(path: Path, title: str, source: str, diagram: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"# {title}\n\n"
        f"Generated by `scripts/export_graph_mermaid.py` from `{source}`. Do not edit by hand.\n\n"
        "```mermaid\n" + diagram + "\n```\n",
        encoding="utf-8",
    )
    print(f"written {path}")


def export_application_graph() -> None:
    deps = GraphDeps(
        fetch_page=_unused,
        analyze=_unused,
        research=_unused,
        retrieve=lambda *_: [],
        tailor=_unused,
        draft=_unused,
        verify=lambda *_: [],
        persist=_unused,
        on_step=_unused,
        max_revisions=2,
    )
    diagram = build_application_graph(deps).get_graph().draw_mermaid()
    _write(
        GRAPHS_DIR / "application_graph.md",
        "Application preparation graph",
        "backend/src/linkedin_agent/graphs/application_graph.py",
        diagram,
    )


def export_research_graph() -> None:
    deps = ResearchDeps(
        plan=_unused,
        search=_unused,
        read=_unused,
        reflect=_unused,
        synthesize=_unused,
        draft=_unused,
        save_draft=_unused,
        on_step=_unused,
        limits=ResearchLimits(
            max_loops=2,
            max_queries=3,
            results_per_query=5,
            max_sources=8,
            max_pages=4,
            page_max_chars=1500,
            context_max_chars=9000,
            min_relevance=0.3,
            min_title_matches=2,
            require_citations=True,
        ),
        languages=DEFAULT_RESEARCH_LANGUAGES,
        default_language="en",
    )
    diagram = build_research_graph(deps).get_graph().draw_mermaid()
    _write(
        GRAPHS_DIR / "research_graph.md",
        "Research agent graph",
        "backend/src/linkedin_agent/graphs/research_graph.py",
        diagram,
    )


def export_watch_graph() -> None:
    deps = WatchDeps(
        search=_unused,
        read=_unused,
        score=_unused,
        route=_unused,
        known_links=_unused,
        persist=_unused,
        on_step=_unused,
        limits=WatchLimits(
            max_queries=4,
            max_regions=2,
            results_per_query=5,
            max_candidates=12,
            max_pages=4,
            page_max_chars=1500,
            batch_size=6,
            snippet_score_cap=60,
            min_score=50,
            min_relevance=0.3,
            min_title_matches=1,
            templates=(),
        ),
        stopwords=frozenset(),
    )
    diagram = build_watch_graph(deps).get_graph().draw_mermaid()
    _write(GRAPHS_DIR / "watch_graph.md", "Watch graph", "backend/src/linkedin_agent/graphs/watch_graph.py", diagram)


def main() -> None:
    export_application_graph()
    export_research_graph()
    export_watch_graph()


if __name__ == "__main__":
    main()
