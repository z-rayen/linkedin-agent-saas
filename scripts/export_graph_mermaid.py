"""Generate the Mermaid diagram of the application graph from the code itself.

Run from the repository root:
    PYTHONPATH=backend/src python scripts/export_graph_mermaid.py

The structure comes from build_graph(); no dependency is called. The output is docs/graphs/application_graph.md.
"""

from pathlib import Path

from linkedin_agent.graphs.application_graph import GraphDeps, build_graph

OUTPUT = Path(__file__).resolve().parents[1] / "docs" / "graphs" / "application_graph.md"


async def _unused(*_: object) -> None:
    raise RuntimeError("structure export only: no dependency may be called")


def main() -> None:
    deps = GraphDeps(
        fetch_page=_unused,
        analyze=_unused,
        research=_unused,
        retrieve=lambda *_: [],
        tailor=_unused,
        draft=_unused,
        verify=lambda *_: [],
        persist=_unused,
        on_step=_unused,
        max_revisions=2,
    )
    diagram = build_graph(deps).get_graph().draw_mermaid()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "# Application preparation graph\n\n"
        "Generated by `scripts/export_graph_mermaid.py` from `backend/src/linkedin_agent/graphs/application_graph.py`. "
        "Do not edit by hand.\n\n```mermaid\n" + diagram + "\n```\n",
        encoding="utf-8",
    )
    print(f"written {OUTPUT}")


if __name__ == "__main__":
    main()
